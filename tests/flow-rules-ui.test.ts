import test from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, mkdir, readFile, realpath, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, extname } from "node:path";
import { createServer, type ServerResponse } from "node:http";
import { setTimeout as delay } from "node:timers/promises";
import { chromium, expect } from "@playwright/test";
import { initialState } from "../packages/contracts/defaults.js";
import { settingsSchema, type Run, type Step } from "../packages/contracts/index.ts";
import { Studio } from "../packages/engine/studio.ts";
import { Store } from "../packages/engine/store.ts";

test("Flow controls save isolated rules and drive plan review, revisions and final approval", { timeout: 45000 }, async t => {
  const root = await realpath(await mkdtemp(join(tmpdir(), "studio-flow-ui-"))), cwd = join(root, "project");
  await mkdir(cwd); await writeFile(join(cwd, "README.md"), "Fixture project");
  const store = new Store(join(root, "state.sqlite"));
  const studio = new Studio(store, root, join(root, "sockets"));
  const settings = settingsSchema.parse(initialState());
  settings.agents = settings.agents.slice(0, 3).map(agent => ({ ...agent, provider: "codex", tools: ["read"] }));
  settings.flows = ["main", "other"].map(id => ({ id, name: id === "main" ? "Delivery" : "Other flow", workflow: settings.agents.map(agent => agent.id), rules: [], revision: 1, archived: false }));
  settings.activeFlowId = "main"; settings.skillRoots = []; settings.approvalRequired = false;
  settings.projects = [{ id: "fixture", name: "Fixture", path: cwd, execution: { mode: "local", branchName: "" } }]; settings.activeProjectId = "fixture";
  store.set("settings", settings);
  store.set("connections", [{ id: "codex-subscription", provider: "codex", auth: "subscription", models: ["default"], connected: true, billingMode: "subscription" }]);
  studio.connections.assertAgent = async () => {};
  studio.catalog.scan = async () => ({ skills: [], sources: [], errors: [] }) as any;
  const calls: Step[] = [];
  let reviewerPasses = false, askDecisions = false;
  const decision = { id: "D1", question: "Select the response contract", options: ["A: HTTP 200 after commit", "B: HTTP 202 with a reservation"], recommendation: "B keeps asynchronous requests responsive.", blocking: true };
  t.mock.method(studio as any, "codexTurn", async (run: Run, step: Step) => {
    step.providerThreadId ??= `provider-${step.id}`;
    calls.push(structuredClone(step));
    const decision = step.agent.role === "reviewer" && !reviewerPasses ? "revise" : "pass";
    const names = step.agent.role === "planner" ? ["implementation-plan.md", "qa-sheet.md"] : [`${step.agent.role}.md`];
    const result = JSON.stringify({ status: "completed", decision, decisions: askDecisions && step.agent.role === "planner" && !run.followup ? [{ id: "D1", question: "Select the response contract", options: ["A: HTTP 200 after commit", "B: HTTP 202 with a reservation"], recommendation: "B keeps asynchronous requests responsive.", blocking: true }] : [], summary: run.followup ? "Updated Redis plan ready for review" : decision === "pass" ? "Ready for review" : "Fix the duplicate request case", artifacts: names.map(name => ({ name, type: "Report", content: run.followup ? `${name}: Redis revision` : `${name}: draft ${step.attempt || 1}` })) });
    step.messages.push({ id: step.id, type: "assistant", text: result, time: new Date().toISOString() });
    return result;
  });
  const streams = new Set<ServerResponse>();
  const methods: Record<string, string> = { settings: "settings.save", catalog: "catalog", snapshots: "snapshots", project: "project", "runs/start": "run.start", "runs/control": "run.control", "runs/read": "run.read", "runs/message": "run.message" };
  const server = createServer(async (req, res) => {
    try {
      const path = new URL(req.url!, "http://localhost").pathname;
      if (path === "/api/events") {
        res.writeHead(200, { "Content-Type": "text/event-stream", "Cache-Control": "no-cache" }); res.write(": connected\n\n");
        streams.add(res); req.on("close", () => streams.delete(res)); return;
      }
      if (path.startsWith("/api/")) {
        let data;
        if (path === "/api/bootstrap") data = { csrf: "fixture", state: store.state() };
        else if (path === "/api/status") data = { service: "agent-studio", roots: [] };
        else {
          let body = ""; for await (const part of req) body += part;
          const method = methods[path.slice(5)]; assert(method, `Unexpected test request: ${path}`);
          data = await studio.dispatch(method, JSON.parse(body || "{}"));
          if (path === "/api/runs/control") await delay(60);
        }
        res.writeHead(200, { "Content-Type": "application/json" }); res.end(JSON.stringify(data)); return;
      }
      const file = path === "/" ? "index.html" : path.slice(1);
      assert(!file.includes(".."));
      const types: Record<string, string> = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css", ".svg": "image/svg+xml" };
      res.writeHead(200, { "Content-Type": types[extname(file)] || "application/octet-stream" }); res.end(await readFile(join(process.cwd(), "dist/web", file)));
    } catch (error) { res.writeHead(400, { "Content-Type": "application/json" }); res.end(JSON.stringify({ error: (error as Error).message })); }
  });
  store.on("event", event => { for (const stream of streams) stream.write(`id: ${event.seq}\nevent: run\ndata: ${JSON.stringify(store.state().run)}\n\n`); });
  await new Promise<void>(resolve => server.listen(0, "127.0.0.1", resolve));
  const browser = await chromium.launch(), page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  t.after(async () => { await browser.close(); for (const stream of streams) stream.end(); server.closeAllConnections(); await new Promise<void>(resolve => server.close(() => resolve())); await studio.close(); store.close(); await rm(root, { recursive: true, force: true }); });
  page.setDefaultTimeout(5000);
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${(server.address() as { port: number }).port}`);
  await expect(page.locator(".sidebar-status")).toContainText("Local skills connected");
  const choose = async (name: string, value: string) => {
    await page.getByRole("combobox", { name, exact: true }).click();
    await page.getByRole("option", { name: value, exact: true }).click();
  };
  const flow = () => studio.settings().flows.find(item => item.id === "main")!;
  const openStep = async (name: string) => page.getByRole("button", { name: `Step settings for ${name}`, exact: true }).click();
  const saveRule = async () => { await page.getByRole("button", { name: "Save flow rules", exact: true }).click(); await expect(page.locator("#toast")).toHaveText("Flow rules saved for new tasks."); };
  await page.getByRole("button", { name: "Flows", exact: true }).click();
  await openStep("Planner");
  await choose("Human checkpoint", "Review before continuing");
  await page.getByLabel("Lock reviewed outputs").check();
  await saveRule();
  assert.equal(flow().rules[0].lockOutputs, true);
  await openStep("Reviewer");
  await choose("Human checkpoint", "Review before continuing");
  await choose("If the result needs changes", "Coder");
  await page.getByLabel("Maximum automatic revisions").fill("1");
  await saveRule();
  assert.equal(flow().rules[1].loop?.maxCycles, 1);
  await page.locator('[data-action="select-flow"][data-id="other"]').click();
  await openStep("Planner"); await expect(page.locator('[name="review"]')).toHaveValue("auto");
  assert.deepEqual(studio.settings().flows[1].rules, []);
  await page.locator('[data-action="select-flow"][data-id="main"]').click();
  await openStep("Coder"); await page.getByRole("button", { name: "Remove from flow", exact: true }).click();
  await expect(page.locator("#toast")).toContainText("earlier step");
  assert.equal(flow().workflow.length, 3);
  const downloadPromise = page.waitForEvent("download"); await page.getByRole("button", { name: "Export", exact: true }).click();
  const downloaded = await downloadPromise; const exported = JSON.parse(await readFile((await downloaded.path())!, "utf8"));
  assert.deepEqual(exported.rules, flow().rules);
  await page.getByRole("button", { name: "Use this flow", exact: true }).click();
  await page.getByLabel("Task brief", { exact: true }).fill("Implement a duplicate-safe request");
  await page.getByRole("button", { name: "Run task", exact: true }).click();
  await expect(page.getByRole("button", { name: "Lock and continue", exact: true })).toBeVisible();
  assert.deepEqual(calls.map(step => step.agent.id), ["planner"]);
  await expect(page.getByRole("heading", { name: "Review the plan together", exact: true })).toBeVisible();
  await page.getByLabel("Questions or changes for the plan", { exact: true }).fill("Include concurrent duplicate requests");
  await page.getByRole("button", { name: "Request revision", exact: true }).click();
  await expect(page.locator(".review-heading")).toContainText("Draft 2");
  assert.equal(calls.at(-1)?.feedback, "Include concurrent duplicate requests");
  await page.getByText("Compare with previous draft", { exact: true }).first().click();
  await expect(page.locator(".review-diff").first()).toContainText("draft 1");
  await page.reload();
  await page.locator(".recent-work").getByRole("button", { name: /Implement a duplicate-safe request/ }).click();
  await page.getByRole("button", { name: "Review outputs", exact: true }).click();
  await expect(page.locator(".review-heading")).toContainText("Draft 2");
  await page.getByLabel("Questions or changes for the plan", { exact: true }).fill("Revise the plan and QA sheet to use Redis.");
  await page.getByRole("button", { name: "Send question", exact: true }).click();
  await expect.poll(() => store.state().run!.followup).toBeUndefined();
  await page.getByRole("button", { name: "Review outputs", exact: true }).click();
  await expect(page.locator(".review-heading")).toContainText("Draft 3");
  await expect(page.locator(".review-summary")).toContainText("Updated Redis plan");
  await expect(page.locator(".review-document-body").first()).toContainText("Redis revision");
  assert.ok(calls.every(step => step.agent.role === "planner"));
  const revisedIds = store.state().run!.review!.artifactIds;
  await page.getByRole("button", { name: "Lock only", exact: true }).click();
  await expect(page.getByRole("button", { name: "Resume", exact: true })).toBeVisible();
  assert.equal(calls.length, 3);
  assert.equal(store.state().run!.lockedPlan!.version, 3);
  assert.deepEqual(store.state().run!.lockedPlan!.artifactIds, revisedIds);
  await page.getByRole("button", { name: "Resume", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Choose the next revision", exact: true })).toBeVisible();
  assert.equal(calls.filter(step => step.agent.role === "coder").length, 2);
  await expect(page.getByRole("button", { name: "Approve and continue", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Attempts", exact: true }).click();
  await expect(page.locator(".attempts-list")).toContainText("Attempt 1");
  await expect(page.locator(".attempts-list")).toContainText("Attempt 2");
  await page.getByRole("button", { name: "Flows", exact: true }).click();
  await openStep("Reviewer"); await page.getByLabel("Maximum automatic revisions").fill("4");
  store.saveRun(await studio.dispatch("run.read", { id: store.state().run!.id }), "ui.refresh");
  await expect(page.getByLabel("Maximum automatic revisions")).toHaveValue("4");
  await saveRule();
  assert.equal(flow().rules[1].loop?.maxCycles, 4);
  assert.equal(store.state().run!.flow.rules[1].loop!.maxCycles, 1);
  await page.locator('[data-action="navigate"][data-view="runs"]').click();
  await page.locator(`.history-table [data-action="open-run"][data-id="${store.state().run!.id}"]`).click();
  await page.getByRole("button", { name: "Review outputs", exact: true }).click();
  reviewerPasses = true;
  await page.locator("#review-feedback").fill("Use an atomic claim before processing");
  await page.getByRole("button", { name: "Run one more revision", exact: true }).click();
  await expect(page.getByRole("button", { name: "Approve and continue", exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole("button", { name: "Approve and continue", exact: true })).toBeVisible();
  await expect.poll(async () => { const box = await page.locator(".review-workspace").boundingBox(); return box ? box.x + box.width : Infinity; }).toBeLessThanOrEqual(390);
  await page.getByRole("button", { name: "Approve and continue", exact: true }).click();
  await expect.poll(() => store.state().run!.status).toBe("succeeded");
  assert.equal(calls.filter(step => step.agent.role === "coder").length, 3);
  assert.equal(store.state().run!.reviewHistory!.at(-1)!.action, "approved");
  askDecisions = true;
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole("button", { name: "New task", exact: true }).click();
  await page.getByLabel("Task brief", { exact: true }).fill("Plan an asynchronous API with user decisions");
  await page.getByRole("button", { name: "Run task", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Your decisions are needed before coding", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Lock and continue", exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Lock only", exact: true })).toBeDisabled();
  await expect(page.getByRole("textbox", { name: "Answer for D1", exact: true })).toBeEmpty();
  await page.getByRole("button", { name: "Update plan with answers", exact: true }).click();
  await expect(page.locator("#toast")).toHaveText("Answer at least one decision.");
  await page.getByRole("button", { name: decision.options[1], exact: true }).click();
  await expect(page.getByRole("textbox", { name: "Answer for D1", exact: true })).toHaveValue(decision.options[1]);
  await expect(page.getByRole("button", { name: "Lock and continue", exact: true })).toBeDisabled();
  const pending = store.state().run!;
  store.saveRun(await studio.dispatch("run.read", { id: pending.id }), "ui.refresh");
  await expect(page.getByRole("textbox", { name: "Answer for D1", exact: true })).toHaveValue(decision.options[1]);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(async () => { const box = await page.locator(".review-decisions").boundingBox(); return box ? box.x + box.width : Infinity; }).toBeLessThanOrEqual(390);
  await page.getByRole("button", { name: "Update plan with answers", exact: true }).click();
  await expect.poll(() => store.state().run!.review!.id).not.toBe(pending.review!.id);
  await expect.poll(() => store.state().run!.followup).toBeUndefined();
  assert.equal(store.state().run!.steps[1].status, "queued");
  assert.match(store.state().run!.steps[0].messages.findLast(message => message.type === "user")!.text, /Answer: B: HTTP 202/);
  await page.getByRole("button", { name: "Review outputs", exact: true }).click();
  await expect(page.getByRole("button", { name: "Lock and continue", exact: true })).toBeEnabled();
  assert.equal(store.state().run!.lockedPlan, undefined);
  await page.getByRole("button", { name: "Lock only", exact: true }).click();
  await expect.poll(() => store.state().run!.status).toBe("paused");
  assert.deepEqual(errors, []);
});
