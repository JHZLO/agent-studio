import test from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, mkdir, readFile, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawn } from "node:child_process";
import { createServer } from "node:http";
import { setTimeout as delay } from "node:timers/promises";
import { chromium, expect } from "@playwright/test";
import { initialState } from "../packages/contracts/defaults.js";
import { settingsSchema, type Run } from "../packages/contracts/index.ts";
import { Store, hash } from "../packages/engine/store.ts";
import { codeReference } from "../packages/engine/tools.ts";

test("Korean UI persists its language while keeping agent data and review controls intact", { timeout: 60000 }, async t => {
  const root = await mkdtemp(join(tmpdir(), "studio-i18n-")), cwd = join(root, "project");
  await mkdir(cwd); await writeFile(join(cwd, "README.md"), "Unchanged fixture");
  const store = new Store(join(root, "studio.sqlite")), settings = settingsSchema.parse(initialState());
  settings.skillRoots = [];
  settings.agents[1].name = "New task"; settings.agents[1].prompt = "Keep New task in English. 한국어 지침도 보존하세요.";
  settings.projects = [{ id: "locale-project", name: "New task", path: cwd, execution: { mode: "local", branchName: "" } }]; settings.activeProjectId = "locale-project";
  store.set("settings", settings);
  const artifact = { id: "plan", name: "implementation-plan.md", type: "Report", content: "New task\n사용자가 작성한 계획", agent: "Planner", stepId: "planner-step" };
  const reference = await codeReference(cwd);
  const run: Run = { id: "locale-review", brief: "New task", createdAt: new Date().toISOString(), project: settings.projects[0], flow: { ...settings.flows[0], workflow: ["planner"] }, cwd, baseHead: null, status: "waiting_review", index: 1, steps: [{ id: "planner-step", agent: settings.agents[0], sessionId: "planner-session", status: "succeeded", receivedArtifacts: [], messages: [{ id: "m", type: "assistant", text: "New task", time: new Date().toISOString() }], codeReference: reference }], artifacts: [artifact], note: "", approvalRequired: true, approved: false, pauseRequested: false, controlMode: "studio", eventSeq: 0, commandId: "fixture", review: { id: "review", stepId: "planner-step", kind: "checkpoint", artifactIds: [artifact.id], fingerprint: hash(JSON.stringify([[artifact.id, artifact.content]])), version: 1, returnTo: "planner", lockOutputs: true, summary: "New task", createdAt: new Date().toISOString(), codeReference: reference } };
  store.saveRun(run, "review.requested"); store.close();
  const reserve = createServer(); await new Promise<void>(resolve => reserve.listen(0, "127.0.0.1", resolve));
  const port = (reserve.address() as { port: number }).port; await new Promise<void>(resolve => reserve.close(() => resolve()));
  const api = spawn(process.execPath, ["--import", "tsx", "apps/server/main.ts"], { cwd: process.cwd(), env: { ...process.env, AGENT_STUDIO_DATA_DIR: root, AGENT_STUDIO_PORT: String(port), CODEX_HOME: join(root, "codex"), CLAUDE_CONFIG_DIR: join(root, "claude") }, stdio: "ignore" });
  const browser = await chromium.launch();
  t.after(async () => {
    await browser.close(); api.kill("SIGTERM");
    try { process.kill(JSON.parse(await readFile(join(root, "runner.lock"), "utf8")).pid, "SIGTERM"); } catch {}
    for (let i = 0; i < 50; i++) { try { await readFile(join(root, "runner.lock")); await delay(100); } catch { break; } }
    await rm(root, { recursive: true, force: true });
  });
  const origin = `http://127.0.0.1:${port}`;
  for (let i = 0; i < 100; i++) { try { if ((await fetch(origin + "/api/bootstrap")).ok) break; } catch {} await delay(100); }
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } }); page.setDefaultTimeout(5000);
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto(origin);
  const current = async () => (await (await page.request.get(origin + "/api/state")).json());
  const choose = async (label: string, option: string) => { await page.getByRole("combobox", { name: label, exact: true }).click(); await page.getByRole("option", { name: option, exact: true }).click(); };
  await page.getByRole("button", { name: "Defaults", exact: true }).click();
  await choose("Display language", "한국어");
  await expect(page.locator("html")).toHaveAttribute("lang", "ko");
  await expect.poll(async () => (await current()).language).toBe("ko");
  assert.deepEqual((await current()).agents, settings.agents);
  await page.reload();
  await expect(page.locator('[data-action="project-picker"]')).toHaveText("New task");
  await page.getByRole("button", { name: "기본 설정", exact: true }).click();
  await expect(page.locator("#ui-language")).toHaveValue("ko");
  for (const label of ["새 작업", "플로우", "에이전트 라이브러리", "스킬 라이브러리", "연결"]) await expect(page.getByRole("button", { name: label, exact: true }).first()).toBeVisible();
  await page.getByRole("button", { name: "에이전트 라이브러리", exact: true }).click();
  const card = page.locator(".agent-card").filter({ has: page.getByRole("heading", { name: "New task", exact: true }) });
  await card.getByRole("button", { name: "에이전트 편집", exact: true }).click();
  await expect(page.getByLabel("지침", { exact: true })).toHaveValue(settings.agents[1].prompt);
  await choose("권한 수준", "읽기 전용");
  await expect(page.locator('[name="permissionLevel"]')).toHaveValue("read-only");
  await page.getByRole("button", { name: "취소", exact: true }).click();
  assert.deepEqual((await current()).agents, settings.agents);
  await card.getByRole("button", { name: "에이전트 편집", exact: true }).click();
  await page.getByLabel("이름", { exact: true }).fill("한글 코더");
  await page.getByLabel("지침", { exact: true }).fill("기존 동작을 유지하세요. New task");
  await page.getByRole("button", { name: "에이전트 저장", exact: true }).click();
  await expect.poll(async () => (await current()).agents[1].name).toBe("한글 코더");
  assert.equal((await current()).agents[1].prompt, "기존 동작을 유지하세요. New task");
  await page.getByRole("button", { name: "작업", exact: true }).click();
  await page.locator('[data-action="open-run"][data-id="locale-review"]').click();
  await expect(page.getByRole("heading", { name: "New task", exact: true }).first()).toBeVisible();
  await expect(page.locator(".review-document pre").first()).toHaveText(artifact.content);
  await expect(page.getByRole("button", { name: "확정 후 계속", exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(async () => { const bounds = await page.locator(".review-workspace").boundingBox(); return !!bounds && bounds.x >= 0 && bounds.x + bounds.width <= 390; }).toBe(true);
  await page.getByRole("button", { name: "확정만 하기", exact: true }).click();
  await expect.poll(async () => (await current()).run.status).toBe("paused");
  assert.equal((await current()).run.approved, false);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.reload();
  await page.getByRole("button", { name: "기본 설정", exact: true }).click();
  await choose("화면 언어", "English");
  await expect(page.getByRole("button", { name: "Agent library", exact: true })).toBeVisible();
  await expect.poll(async () => (await current()).language).toBe("en");
  await page.reload(); await expect(page.locator("html")).toHaveAttribute("lang", "en");
  assert.equal((await current()).agents[1].name, "한글 코더");
  assert.deepEqual(errors, []);
});
